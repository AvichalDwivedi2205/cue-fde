import nextEnv from "@next/env";
nextEnv.loadEnvConfig(process.cwd());
const { slackConfig } = await import("../../lib/integration-config");
const { memberDigest } = await import("../../lib/slack-digest");
const { slackMember } = await import("../../lib/roles");
const config = await slackConfig();
if (!config) throw new Error("Slack not configured");
const members = (config as unknown as { members?: { slackId: string; role: string }[] }).members ?? [];
console.log("saved members:", members.map((m) => `${m.slackId}:${m.role}`).join(", ") || "NONE");
const uid = members[0]?.slackId;
if (!uid) throw new Error("no saved member to test with");
console.log("slackMember gate:", slackMember(config, uid) ? "PASS member recognized" : "FAIL");
const all = await memberDigest(config, uid);
console.log("--- /cue ---");
console.log(all.text);
const filtered = await memberDigest(config, uid, "Notes");
console.log("--- /cue Notes ---");
console.log(filtered.text);
const unknown = await memberDigest(config, uid, "no-such-app");
console.log("--- /cue no-such-app ---");
console.log(unknown.text);
const stranger = await memberDigest(config, "U999999FAKE");
console.log("--- unknown user ---");
console.log(stranger.text);
